std::string module_symbol_base(const std::string& module_name) {
  if (module_name.empty()) {
    throw std::invalid_argument("empty module name");
  }
  std::string out = "goal_";
  for (unsigned char c : module_name) {
    if (std::isalnum(c)) {
      out.push_back((char)c);
    } else if (c == '_') {
      out += "__";
    } else if (c == '-') {
      out += "_d";
    } else {
      out += fmt::format("_x{:02x}", c);
    }
  }
  return out;
}

SignedModule emit_signed_module(const std::string& module_name,
                                std::span<const uint8_t> object_bytes,
                                const SignedModuleOptions& options) {
  if (!options.function_type || (options.function_type & 3)) {
    throw std::invalid_argument("function type must be a non-zero, 4-byte aligned GOAL offset");
  }
  const V3Object obj = parse_v3_object(object_bytes);

  SignedModule mod;
  mod.name = module_name;
  mod.symbol_base = module_symbol_base(module_name);
  mod.sha256 = sha256::hex_digest(object_bytes);
  mod.manifest["name"] = module_name;
  mod.manifest["sha256"] = mod.sha256;
  mod.manifest["segments"] = nlohmann::json::array();

  std::ostringstream text;
  std::ostringstream templates;
  text << fmt::format("// {} (sha256 {}), generated by jak2-aot-emit\n", module_name, mod.sha256);
  text << ".section __GOAL,__text,regular,pure_instructions\n";

  for (int seg_id = 0; seg_id < N_SEG; seg_id++) {
    const V3Segment& seg = obj.segments[seg_id];
    SignedSegment& out = mod.segments[seg_id];
    if (seg.data.empty() || (seg_id == DEBUG_SEGMENT && options.omit_debug_segment)) {
      continue;
    }
    out.present = true;
    out.code_size = seg.executable_size;
    out.static_size = seg.static_size();
    const std::string stem = fmt::format("{}_s{}", mod.symbol_base, seg_id);
    if (out.code_size) {
      out.text_symbol = stem + "_text";
    }
    if (out.static_size) {
      out.data_symbol = stem + "_data";
      out.template_symbol = stem + "_template";
    }
    const uint32_t exec = seg.executable_size;
    auto where = [&](uint32_t offset) {
      return fmt::format("{} {} offset {:#x}", module_name, SEGMENT_NAMES[seg_id], offset);
    };
    auto require_data = [&](uint32_t offset, const char* what) {
      if (offset < exec) {
        throw std::runtime_error(fmt::format(
            "{}: {} patches signed code, which must stay read-only", where(offset), what));
      }
      return offset - exec;
    };

    // Function type tags are the only link records allowed inside the code.
    std::set<uint32_t> function_tags;
    nlohmann::json types = nlohmann::json::array();
    for (const auto& t : seg.type_links) {
      nlohmann::json data_offsets = nlohmann::json::array();
      for (auto offset : t.offsets) {
        if (offset < exec) {
          if (t.name != "function") {
            throw std::runtime_error(
                fmt::format("{}: type link to '{}' inside code", where(offset), t.name));
          }
          function_tags.insert(offset);
        } else {
          data_offsets.push_back(offset - exec);
        }
      }
      if (!data_offsets.empty()) {
        types.push_back(
            {{"name", t.name}, {"method_count", t.method_count}, {"offsets", data_offsets}});
      }
    }

    nlohmann::json symbols = nlohmann::json::array();
    for (const auto& s : seg.symbol_links) {
      nlohmann::json links = nlohmann::json::array();
      for (auto offset : s.offsets) {
        uint32_t data_offset = require_data(offset, "symbol link");
        links.push_back(
            {{"offset", data_offset}, {"mode", symbol_mode(word_at(seg.data, offset))}});
      }
      symbols.push_back({{"name", s.name}, {"links", links}});
    }

    nlohmann::json pointers = nlohmann::json::array();
    for (const auto& p : seg.pointer_links) {
      uint32_t patch = require_data(p.source, "pointer link");
      bool to_code = p.dest < exec;
      pointers.push_back({{"patch", patch},
                          {"target_region", to_code ? "code" : "data"},
                          {"target", to_code ? p.dest : p.dest - exec}});
    }

    nlohmann::json distances = nlohmann::json::array();
    for (const auto& d : seg.distance_links) {
      uint32_t patch = require_data(d.patch, "distance link");
      uint32_t source = require_data(d.source, "distance link source");
      const auto& target_seg = obj.segments[d.target_segment];
      bool to_code = d.dest < target_seg.executable_size;
      distances.push_back({{"patch", patch},
                           {"source", source},
                           {"target_segment", d.target_segment},
                           {"target_region", to_code ? "code" : "data"},
                           {"target", to_code ? d.dest : d.dest - target_seg.executable_size}});
    }

    // Code.
    if (out.code_size) {
      text << ".p2align 4\n";
      text << fmt::format(".globl _{}\n_{}:\n", out.text_symbol, out.text_symbol);
      WordWriter words(text);
      for (uint32_t pc = 0; pc < exec; pc += 4) {
        const uint32_t w = word_at(seg.data, pc);
        if (function_tags.count(pc)) {
          words.word(options.function_type);
          continue;
        }
        if (is_adrp(w)) {
          if (pc + 8 > exec) {
            throw std::runtime_error(fmt::format("{}: ADRP without a pair", where(pc)));
          }
          const uint32_t lo = word_at(seg.data, pc + 4);
          const uint32_t rd = w & 31;
          if (((lo >> 5) & 31) != rd || !(is_ldr64_uimm(lo) || is_add_imm(lo))) {
            throw std::runtime_error(
                fmt::format("{}: ADRP is not followed by LDR/ADD of the same register", where(pc)));
          }
          const int64_t pages = sign_extend((((w >> 5) & 0x7FFFF) << 2) | ((w >> 29) & 3), 21);
          const uint32_t lo12 = (lo >> 10) & 0xFFF;
          const int64_t target =
              ((int64_t)pc & ~0xFFFll) + pages * 0x1000 + (is_ldr64_uimm(lo) ? 8 * lo12 : lo12);
          if (target < exec || target >= (int64_t)seg.data.size()) {
            throw std::runtime_error(fmt::format(
                "{}: ADRP pair targets {:#x}, outside the static data", where(pc), target));
          }
          const std::string ref = fmt::format("{}+{:#x}", out.data_symbol, target - exec);
          words.flush();
          text << fmt::format("  adrp {}, _{}@PAGE\n", reg(rd, module_name, pc), ref);
          if (is_ldr64_uimm(lo)) {
            text << fmt::format("  ldr {}, [{}, _{}@PAGEOFF]\n", reg(lo & 31, module_name, pc),
                                reg(rd, module_name, pc), ref);
          } else {
            text << fmt::format("  add {}, {}, _{}@PAGEOFF\n", reg(lo & 31, module_name, pc),
                                reg(rd, module_name, pc), ref);
          }
          pc += 4;
          continue;
        }
        if (is_ldr_literal(w) || is_adr(w)) {
          throw std::runtime_error(
              fmt::format("{}: PC-relative literal reference; compile with --arm64-code-model page",
                          where(pc)));
        }
        words.word(w);
      }
      words.flush();
    }

    // Static data template.
    if (out.static_size) {
      templates << ".p2align 4\n";
      templates << fmt::format(".globl _{}\n_{}:\n", out.template_symbol, out.template_symbol);
      WordWriter words(templates);
      uint32_t offset = exec;
      for (; offset + 4 <= seg.data.size(); offset += 4) {
        words.word(word_at(seg.data, offset));
      }
      words.flush();
      for (; offset < seg.data.size(); offset++) {
        templates << fmt::format("  .byte 0x{:02x}\n", seg.data[offset]);
      }
    }

    mod.manifest["segments"].push_back({{"index", seg_id},
                                        {"name", SEGMENT_NAMES[seg_id]},
                                        {"code_size", out.code_size},
                                        {"static_size", out.static_size},
                                        {"text_symbol", out.text_symbol},
                                        {"data_symbol", out.data_symbol},
                                        {"template_symbol", out.template_symbol},
                                        {"function_tags", function_tags.size()},
                                        {"symbols", symbols},
                                        {"types", types},
                                        {"pointers", pointers},
                                        {"distances", distances}});
  }

  mod.assembly = text.str();
  const std::string tmpl = templates.str();
  if (!tmpl.empty()) {
    mod.assembly += ".section __TEXT,__const\n" + tmpl;
  }
  return mod;
}

ArenaLayout emit_arena_layout(std::span<const SignedModule> modules, const ArenaOptions& options) {
  const uint32_t align = options.alignment;
  if (!align || (align & (align - 1)) || options.data_base % align ||
      options.data_base >= options.data_limit || options.data_limit > options.arena_size) {
    throw std::invalid_argument("invalid arena layout options");
  }
  ArenaLayout layout;
  std::ostringstream out;
  out << "// EE arena and fixed module data locations, generated by jak2-aot-emit\n";
  out << fmt::format(".zerofill __ARENA,__arena,_goal_aot_arena,{:#x},14\n", options.arena_size);
  out << ".globl _goal_aot_arena\n";
  uint64_t cursor = options.data_base;
  for (const auto& mod : modules) {
    for (int seg_id = 0; seg_id < N_SEG; seg_id++) {
      const auto& seg = mod.segments[seg_id];
      if (!seg.present || !seg.static_size) {
        continue;
      }
      cursor = (cursor + align - 1) & ~uint64_t(align - 1);
      out << fmt::format(".globl _{}\n.set _{}, _goal_aot_arena + {:#x}\n", seg.data_symbol,
                         seg.data_symbol, cursor);
      layout.manifest[mod.name][SEGMENT_NAMES[seg_id]] = cursor;
      cursor += seg.static_size;
      if (cursor > options.data_limit) {
        throw std::runtime_error(
            fmt::format("module data does not fit in [{:#x}, {:#x}): {} needs {:#x}",
                        options.data_base, options.data_limit, mod.name, cursor));
      }
    }
  }
  layout.data_end = (uint32_t)cursor;
  layout.assembly = out.str();
  return layout;
}

namespace {
struct BankSpec {
  const char* name;
  uint32_t count;
};

std::array<BankSpec, 4> bank_specs(const ExportBankOptions& options) {
  return {{{"arg", options.arg_count},
           {"arg_pp", options.arg_pp_count},
           {"stack", options.stack_count},
           {"mips2c", options.mips2c_count}}};
}

constexpr uint32_t kBankStride = 32;
}  // namespace

std::string emit_export_banks(const ExportBankOptions& options) {
  if (!options.function_type || (options.function_type & 3)) {
    throw std::invalid_argument("function type must be a non-zero, 4-byte aligned GOAL offset");
  }
  std::ostringstream out;
  out << "// Signed C->GOAL export banks, generated by jak2-aot-emit\n";
  const auto specs = bank_specs(options);
  for (const auto& bank : specs) {
    out << fmt::format(".globl _goal_aot_bank_{0}_slots\n", bank.name);
    out << fmt::format(".zerofill __DATA,__bss,_goal_aot_bank_{}_slots,{:#x},4\n", bank.name,
                       16 * std::max<uint32_t>(bank.count, 1));
  }
  out << ".section __GOAL,__text,regular,pure_instructions\n";
  for (int kind = 0; kind < 4; kind++) {
    const auto& bank = specs[kind];
    out << fmt::format(".p2align 4\n.globl _goal_aot_bank_{0}\n_goal_aot_bank_{0}:\n", bank.name);
    for (uint32_t i = 0; i < bank.count; i++) {
      // Each stub: type tag, then code; padded to kBankStride.
      const std::string slot = fmt::format("_goal_aot_bank_{}_slots+{:#x}", bank.name, 16 * i);
      out << ".p2align 4\n";
      out << fmt::format("  .long {:#010x}\n", options.function_type);
      if (kind == GOAL_AOT_BANK_MIPS2C) {
        out << fmt::format("  adrp x15, {}@PAGE\n  add x15, x15, {}@PAGEOFF\n", slot, slot);
        out << "  ldp x16, x17, [x15]\n";
        out << "  adrp x15, _mips2c_call_arm64@PAGE\n";
        out << "  add x15, x15, _mips2c_call_arm64@PAGEOFF\n  br x15\n";
      } else {
        const char* bridge = kind == GOAL_AOT_BANK_STACK ? "_stack_call_arm64" : "_arg_call_arm64";
        out << fmt::format("  adrp x16, {}@PAGE\n  ldr x16, [x16, {}@PAGEOFF]\n", slot, slot);
        out << (kind == GOAL_AOT_BANK_ARG_PP ? "  mov x3, x20\n" : "  nop\n");
        out << fmt::format("  adrp x17, {0}@PAGE\n  add x17, x17, {0}@PAGEOFF\n  br x17\n", bridge);
      }
    }
  }
  out << ".p2align 4\n.globl _goal_aot_nothing_stub\n_goal_aot_nothing_stub:\n";
  out << fmt::format("  .long {:#010x}\n  ret\n", options.function_type);
  out << ".p2align 4\n.globl _goal_aot_zero_stub\n_goal_aot_zero_stub:\n";
  out << fmt::format("  .long {:#010x}\n  mov x0, #0\n  ret\n", options.function_type);
  return out.str();
}

std::string emit_module_index(std::span<const SignedModule> modules,
                              const ExportBankOptions& banks) {
  const uint32_t function_type = banks.function_type;
  std::ostringstream out;
  out << "// Signed GOAL module table, generated by jak2-aot-emit\n";
  out << "#include \"common/aot/SignedModuleIndex.h\"\n\n";
  for (const auto& mod : modules) {
    for (const auto& seg : mod.segments) {
      if (!seg.text_symbol.empty()) {
        out << fmt::format("extern const uint8_t {}[];\n", seg.text_symbol);
      }
      if (!seg.data_symbol.empty()) {
        out << fmt::format("extern uint8_t {}[];\nextern const uint8_t {}[];\n", seg.data_symbol,
                           seg.template_symbol);
      }
    }
  }
  out << "\nconst struct goal_aot_module goal_aot_modules[] = {\n";
  for (const auto& mod : modules) {
    out << fmt::format("  {{\"{}\", \"{}\", {{\n", mod.name, mod.sha256);
    for (const auto& seg : mod.segments) {
      auto or_null = [](const std::string& s) { return s.empty() ? std::string("0") : s; };
      out << fmt::format("    {{{}, {:#x}, {}, {}, {:#x}}},\n", or_null(seg.text_symbol),
                         seg.code_size, or_null(seg.data_symbol), or_null(seg.template_symbol),
                         seg.static_size);
    }
    out << "  }},\n";
  }
  out << "};\n";
  out << fmt::format("const uint32_t goal_aot_module_count = {};\n", modules.size());
  out << fmt::format("const uint32_t goal_aot_function_type = {:#x};\n\n", function_type);
  const auto specs = bank_specs(banks);
  for (const auto& bank : specs) {
    out << fmt::format(
        "extern const uint8_t goal_aot_bank_{}[];\nextern uint64_t goal_aot_bank_{}_slots[];\n",
        bank.name, bank.name);
  }
  out << "const struct goal_aot_export_bank goal_aot_export_banks[GOAL_AOT_BANK_COUNT] = {\n";
  for (const auto& bank : specs) {
    out << fmt::format("  {{goal_aot_bank_{0}, goal_aot_bank_{0}_slots, {1}, {2}}},\n", bank.name,
                       bank.count, kBankStride);
  }
  out << "};\n";
  return out.str();
}

