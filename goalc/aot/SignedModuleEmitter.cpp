constexpr int kWordsPerLine = 8;

int64_t sign_extend(uint64_t value, int bits) {
  uint64_t sign = 1ull << (bits - 1);
  return (int64_t)((value ^ sign) - sign);
}

bool is_adrp(uint32_t w) {
  return (w & 0x9F000000u) == 0x90000000u;
}
bool is_ldr64_uimm(uint32_t w) {
  return (w & 0xFFC00000u) == 0xF9400000u;
}
bool is_add_imm(uint32_t w) {
  return (w & 0xFFC00000u) == 0x91000000u;
}
bool is_ldr_literal(uint32_t w) {
  return (w & 0x3B000000u) == 0x18000000u;  // LDR/LDRSW/PRFM (literal), GPR and SIMD
}
bool is_adr(uint32_t w) {
  return (w & 0x9F000000u) == 0x10000000u;
}

uint32_t word_at(const std::vector<uint8_t>& data, uint32_t offset) {
  uint32_t w;
  memcpy(&w, data.data() + offset, 4);
  return w;
}

std::string reg(uint32_t id, const std::string& module, uint32_t pc) {
  if (id >= 31) {
    throw std::runtime_error(
        fmt::format("{}: ADRP pair at {:#x} uses register 31, which is not supported", module, pc));
  }
  return fmt::format("x{}", id);
}

class WordWriter {
 public:
  explicit WordWriter(std::ostringstream& out) : m_out(out) {}
  void word(uint32_t w) {
    if (m_count == 0) {
      m_out << "  .long ";
    } else {
      m_out << ",";
    }
    m_out << fmt::format("0x{:08x}", w);
    if (++m_count == kWordsPerLine) {
      flush();
    }
  }
  void flush() {
    if (m_count) {
      m_out << "\n";
      m_count = 0;
    }
  }

 private:
  std::ostringstream& m_out;
  int m_count = 0;
};

const char* symbol_mode(uint32_t template_value) {
  if (template_value == 0xFFFFFFFFu) {
    return "address";
  }
  if (template_value == LINK_SYM_NO_OFFSET_FLAG) {
    return "offset-1";
  }
  return "offset";
}

